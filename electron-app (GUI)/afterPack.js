// electron-builder afterPack hook (Linux only).
//
// Why this exists: on Linux, Chromium's sandbox init happens natively,
// before Electron's JS runs — so app.commandLine.appendSwitch('no-sandbox')
// in electron.js is too late to prevent either of the two failure modes
// we've hit:
//   1. AppImage: chrome-sandbox isn't root:4755 inside the mount, so the
//      SUID sandbox helper aborts on startup.
//   2. .deb (where chrome-sandbox permissions ARE correct): Chromium's
//      separate namespace-based sandbox layer can still fail against
//      Ubuntu 24.04+'s AppArmor restriction on unprivileged user
//      namespaces, surfacing as a confusing /dev/shm shared-memory error.
//
// electron-builder 24.x has no config option that reliably injects
// --no-sandbox at the OS exec level for every launch path (AppImage
// double-click, the installed .deb binary run directly, and the .desktop
// launcher). So instead, this hook runs after packaging but BEFORE the
// AppImage/deb-specific build steps: it renames the real Electron
// executable and replaces it with a wrapper script that execs the real
// binary with --no-sandbox. Because it runs before target-specific
// packaging, both the AppImage and the .deb inherit the wrapped binary
// automatically — no separate per-target patching needed.
const fs = require('fs');
const path = require('path');

exports.default = async function (context) {
  if (context.electronPlatformName !== 'linux') return;

  const appOutDir = context.appOutDir;
  const executableName = context.packager.executableName;
  const realBin = path.join(appOutDir, executableName);
  const wrappedBin = path.join(appOutDir, `${executableName}-bin`);

  if (!fs.existsSync(realBin)) {
    console.warn(`[afterPack] Expected executable not found at ${realBin} — skipping no-sandbox wrap.`);
    return;
  }

  fs.renameSync(realBin, wrappedBin);

  const wrapperScript = `#!/bin/bash
# Auto-generated by afterPack.js — launches the real Electron binary with
# --no-sandbox so the app works regardless of how it's started (AppImage,
# installed .deb binary, or the desktop launcher), without requiring the
# user to type any flags themselves.
DIR="$(cd "$(dirname "\${BASH_SOURCE[0]}")" && pwd)"
exec "$DIR/${executableName}-bin" --no-sandbox "$@"
`;

  fs.writeFileSync(realBin, wrapperScript, { mode: 0o755 });
  console.log(`[afterPack] Wrapped ${executableName} to launch with --no-sandbox.`);
};
